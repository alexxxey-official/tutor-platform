/**
 * Получить список задач с фильтрацией
 */
export function getTasksByFilters({ number, topic, difficulty, search = '' }) {
  return EGE_MATH_TASKS.filter((task) => {
    if (number && Number(number) !== 0 && task.number !== Number(number)) return false;
    if (topic && topic !== 'Все' && task.topic !== topic) return false;
    if (difficulty && difficulty !== 'Все' && task.difficulty !== difficulty) return false;
    if (search) {
      const q = search.toLowerCase();
      const matchText = (task.statement + ' ' + task.tags.join(' ') + ' ' + task.topic + ' ' + task.subtopic).toLowerCase();
      if (!matchText.includes(q)) return false;
    }
    return true;
  });
}

/**
 * Сгенерировать случайный сбалансированный вариант (задачи 1-19 по 1 на каждый номер)
 */
export function generateStandardVariant() {
  const variant = [];
  for (let num = 1; num <= 18; num++) {
    const candidateTasks = EGE_MATH_TASKS.filter((t) => t.number === num);
    if (candidateTasks.length > 0) {
      const randomIdx = Math.floor(Math.random() * candidateTasks.length);
      variant.push(candidateTasks[randomIdx]);
    }
  }
  return variant;
}

/**
 * Расчет первичного и вторичного балла за вариант
 */
export function calculateScores(taskResults) {
  let primaryScore = 0;
  let maxPrimary = 32;

  EGE_MATH_TASKS.forEach((task) => {
    const userAns = taskResults[task.id];
    if (!userAns) return;

    if (task.number <= 11) {
      // 1-я часть (краткий ответ): 1 первичный балл
      const cleanUser = String(userAns.value || '').trim().replace(',', '.');
      const cleanCorrect = String(task.answer).trim().replace(',', '.');
      const cleanAlt = task.answerAlt ? String(task.answerAlt).trim().replace(',', '.') : null;

      if (cleanUser === cleanCorrect || (cleanAlt && cleanUser === cleanAlt)) {
        primaryScore += 1;
      }
    } else {
      // 2-я часть (самопроверка / отметка учителя)
      const points = Number(userAns.points || 0);
      const maxP = TASK_TOPICS[task.number]?.maxPoints || 2;
      primaryScore += Math.min(points, maxP);
    }
  });

  // Примерная таблица перевода первичных баллов в 100-балльную шкалу ЕГЭ
  const conversionTable = {
    0: 0, 1: 6, 2: 11, 3: 17, 4: 22, 5: 27, 6: 34, 7: 40, 8: 46, 9: 52,
    10: 58, 11: 64, 12: 70, 13: 72, 14: 74, 15: 76, 16: 78, 17: 80, 18: 82,
    19: 84, 20: 86, 21: 88, 22: 90, 23: 92, 24: 94, 25: 96, 26: 98, 27: 100, 28: 100, 29: 100, 30: 100, 31: 100, 32: 100
  };

  const final100Score = conversionTable[primaryScore] ?? Math.min(100, primaryScore * 3);

  return { primaryScore, maxPrimary, final100Score };
}
